// Bundles the dedicated server into ONE module Worker: worker.js.
//
//   node infra/cloudflare/air-hockey-server/build.mjs          # write worker.js
//   node infra/cloudflare/air-hockey-server/build.mjs --check  # fail if worker.js is stale
//
// No npm, no wrangler, no bundler: it is string concatenation of
//   1. the SHARED-SIM region of src/net.js (solver, validator, history ring,
//      wire codecs - the very bytes the browser runs),
//   2. src/sim.js    (effect-free table physics port, parity-tested vs game.js),
//   3. src/match.js  (match state machine),
//   4. src/worker.js (Worker + Durable Object glue),
// followed by the module exports. Bug uploads worker.js as-is.
import { readFile, writeFile } from 'node:fs/promises';

const here = new URL('./', import.meta.url);
const read = (rel, base = here) => readFile(new URL(rel, base), 'utf8');

export function sharedRegion(netSource) {
  const a = netSource.indexOf('// <<SHARED-SIM:BEGIN>>');
  const b = netSource.indexOf('// <<SHARED-SIM:END>>');
  if (a < 0 || b < a) throw new Error('SHARED-SIM markers missing from src/net.js');
  return netSource.slice(a, b + '// <<SHARED-SIM:END>>'.length);
}

const TEST_EXPORTS = `
export const __test = {
  Match, simWorld, simStepPhysics, simDriveMallet, simResetPositions, simClampMallet, simCollideMallet,
  simRollServe, simClampTarget, srvWorker, PACES, GOAL_WIDTHS,
  rtEncodeState, rtDecodeState, rtEncodeInput, rtDecodeInput, rtEncodeAck, rtSeqNewer,
  lagEncodeHint, lagDecodeHint, lagValidateContactHint, lagRingNew, lagBuildView, lagApplyContact,
  solveMalletImpulse, constants: { PX, PY, PW, PH, CX, CY, PUCK_R, MALLET_R, PUCK_MAX, SMACK_BONUS, PLAYER_CAP, SUB_HZ, STALL_V, STALL_T, GLUE_HARD_CUTOFF },
  limits: { SRV_DROP_GRACE_MS, SRV_EMPTY_TTL_MS, SRV_LOBBY_TTL_MS, SRV_MATCH_MAX_MS, SRV_COUNT_S, SRV_GOAL_HOLD_S, SRV_GOAL_HOLD_WIN_S },
};
`;

export async function bundle({ test = false } = {}) {
  const repo = new URL('../../../', import.meta.url);
  const [net, sim, match, worker] = await Promise.all([
    read('src/net.js', repo), read('src/sim.js'), read('src/match.js'), read('src/worker.js'),
  ]);
  return [
    '// GENERATED by infra/cloudflare/air-hockey-server/build.mjs - DO NOT EDIT.',
    '// Sources: src/net.js (SHARED-SIM region), src/sim.js, src/match.js, src/worker.js',
    '// Module Worker: default export = fetch handler, named export AirHockeyMatch = Durable Object class.',
    '',
    '/* ===== shared with the browser: src/net.js SHARED-SIM ===== */',
    sharedRegion(net),
    '',
    '/* ===== src/sim.js ===== */', sim,
    '/* ===== src/match.js ===== */', match,
    '/* ===== src/worker.js ===== */', worker,
    'export { AirHockeyMatch };',
    'export default srvWorker;',
    test ? TEST_EXPORTS : '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = new URL('worker.js', here);
  const next = await bundle();
  if (process.argv.includes('--check')) {
    const cur = await readFile(out, 'utf8').catch(() => '');
    if (cur !== next) { console.error('air-hockey-server/worker.js is stale: run `npm run build`'); process.exit(1); }
    console.log('air-hockey-server/worker.js is current');
  } else {
    await writeFile(out, next);
    console.log(`Built air-hockey-server/worker.js (${next.length} bytes)`);
  }
}
